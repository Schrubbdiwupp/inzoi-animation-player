    var cur = 'de';
    var listeners = [];

    function t(key) {
        var s = D[cur] && D[cur][key];
        if (s === undefined) s = D.en[key];
        if (s === undefined) s = key;
        for (var i = 1; i < arguments.length; i++) {
            s = s.split('{' + (i - 1) + '}').join(String(arguments[i]));
        }
        return s;
    }

    function each(attr, fn) {
        var els = document.querySelectorAll('[' + attr + ']');
        for (var i = 0; i < els.length; i++) fn(els[i], els[i].getAttribute(attr));
    }

    function apply() {
        try { document.documentElement.lang = cur; } catch (e) {}
        each('data-i18n',       function (el, k) { el.textContent = t(k); });
        each('data-i18n-title', function (el, k) { el.title = t(k); });
        each('data-i18n-ph',    function (el, k) { el.placeholder = t(k); });
    }

    window.AP_I18N = {
        t: t,
        apply: apply,
        get lang() { return cur; },
        set: function (lang) {
            cur = D[lang] ? lang : 'en';
            apply();
            listeners.forEach(function (fn) { try { fn(cur); } catch (e) {} });
        },
        onChange: function (fn) { listeners.push(fn); },
        languages: Object.keys(D)
    };
